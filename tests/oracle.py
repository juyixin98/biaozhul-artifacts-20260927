"""Independent reference oracle for tests.

This is an *independent* re-implementation of Shamir over the same prime field,
written in the most direct textbook style using only Python's built-in ``pow``
for modular inversion. It deliberately imports **neither** ``galois`` **nor**
any module under ``app.core`` -- the reference answers are therefore not
generated by the system under test. Cross-checking this oracle against the
production kernel (which uses galois) is what makes agreement meaningful:

* same secret recovered from every valid threshold subset,
* identical split/recover constants when both are handed known coefficients,
* plus literal, hard-coded known-answer vectors.
"""
from __future__ import annotations

import secrets as _py_secrets

# Must equal app.core.field.SECP256K1_P, but stated literally here so the oracle
# stays self-contained and a typo in one copy would be caught by a test.
P = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEFFFFFC2F


def inv(a: int) -> int:
    a %= P
    if a == 0:
        raise ZeroDivisionError("inverse of zero")
    # Fermat inverse -- independent mechanism from galois's field division.
    return pow(a, P - 2, P)


def poly_eval(coeffs_desc: list[int], x: int) -> int:
    """coeffs_desc in descending degree order (constant last)."""
    acc = 0
    for c in coeffs_desc:
        acc = (acc * x + c) % P
    return acc


def lagrange_constant(xs: list[int], ys: list[int]) -> int:
    total = 0
    for i in range(len(xs)):
        num = 1
        den = 1
        for j in range(len(xs)):
            if i == j:
                continue
            num = (num * (-xs[j])) % P
            den = (den * (xs[i] - xs[j])) % P
        total = (total + ys[i] * num * inv(den)) % P
    return total


def split(secret_element: int, t: int, n: int, *, seed: int | None = None):
    """Return (xs, ys, coeffs). Deterministic when ``seed`` is supplied.

    With a seed we derive coefficients from a simple LCG purely for repeatable
    fixtures -- never for production randomness.
    """
    if seed is not None:
        state = seed & 0xFFFFFFFFFFFFFFFF
        def rnd() -> int:
            nonlocal state
            # LCG (Knuth) - fixture determinism only.
            state = (state * 6364136223846793005 + 1442695040888963407) & 0xFFFFFFFFFFFFFFFF
            return state % (P - 1) + 1
        coeffs = [rnd() for _ in range(t - 1)]
    else:
        coeffs = [_py_secrets.randbelow(P - 1) + 1 for _ in range(t - 1)]
    coeffs.append(secret_element % P)
    xs = list(range(1, n + 1))
    ys = [poly_eval(coeffs, x) for x in xs]
    return xs, ys, coeffs


def recover(xs: list[int], ys: list[int]) -> int:
    return lagrange_constant(xs, ys)

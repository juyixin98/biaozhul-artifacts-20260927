def test_cyclic_reference_guard_whitebox():
    """The same-position (self) branch cannot be produced by valid encoding:
    a literal self-spend requires an input whose txid equals the spending
    transaction's own txid, i.e. a SHA-256 preimage fixed point. The guard
    therefore exists as defense-in-depth and is exercised directly here.
    """
    sc, alice, genesis = _funded_scenario()
    self_txid = b"\xcc" * 32
    pending = _Pending(created={}, positions={self_txid: 1}, spent_in_block=set())
    with pytest.raises(LedgerError) as ei:
        _resolve_outpoint(
            _op(self_txid, 0),
            tx_index=1,
            view=sc.store,
            pending=pending,
            spend_txid=self_txid,
        )
    assert ei.value.code is ErrorCode.CYCLIC_REFERENCE
    assert ei.value.category.value == "state"



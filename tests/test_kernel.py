def test_wrong_height_and_prev_hash():
    sc, alice, genesis = _funded_scenario()
    # Wrong height (tip is 1): submit raw directly without advancing builder.
    bad_height = Block(
        1, 9, sc.prev_hash,
        (coinbase_tx(9, [(1_000_000, alice.public_bytes)]),),
    )
    pres = sc.node.submit_raw_block(encode_block(bad_height), seq=99)
    assert not pres.accepted
    assert pres.error["code"] == ErrorCode.BLOCK_HEIGHT_INVALID.value
    assert pres.error["category"] == "state"
    assert pres.state_unchanged

    # Correct height but wrong prev_hash.
    bad_prev = Block(
        1, 2, b"\xab" * 32,
        (coinbase_tx(2, [(1_000_000, alice.public_bytes)]),),
    )
    pres2 = sc.node.submit_raw_block(encode_block(bad_prev), seq=100)
    assert not pres2.accepted
    assert pres2.error["code"] == ErrorCode.PREV_BLOCK_HASH_MISMATCH.value
    assert pres2.state_unchanged



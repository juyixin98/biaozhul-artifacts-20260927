"""Kernel + node semantic tests.

Every rejection test asserts three things independently:

1. the production code rejects with the *specific* ``ErrorCode`` and category;
2. the independent oracle (:mod:`tests.oracle`, which imports no production
   module) rejects with the same code and category -- the expected answer is
   never generated by the code under test;
3. the committed UTXO set is byte-for-byte identical before and after, and
   equals the untouched oracle state (whole-block atomicity).

Happy-path tests additionally compare per-transaction intermediate reference
states via the oracle.
"""

from __future__ import annotations

import pytest

from utxo_ledger.encoding import (
    Block,
    Outpoint,
    Transaction,
    TxInput,
    TxOutput,
    encode_block,
    tx_sighash,
)
from utxo_ledger.errors import ErrorCode, LedgerError, category_of
from utxo_ledger.kernel import (
    InMemoryChainView,
    Utxo,
    _Pending,
    _resolve_outpoint,
    checked_add,
)
from utxo_ledger.protocol import MAX_BLOCK_TXS, MAX_MONEY, ZERO_HASH

from tests.fixtures import coinbase_tx, named_key, transfer_tx
from tests.scenarios import Scenario


def _op(txid: bytes, vout: int) -> Outpoint:
    return Outpoint(txid, vout)


def _funded_scenario():
    """One accepted block; alice owns one 1_000_000 UTXO at height 1.

    Returns ``(scenario, alice_keypair, genesis_block)``.
    """
    sc = Scenario()
    alice = named_key("alice")
    block = sc.append([coinbase_tx(1, [(1_000_000, alice.public_bytes)])])
    return sc, alice, block


def _assert_rejected_matches_oracle(res, code: ErrorCode, tx_index=None):
    """Production rejection == independent oracle rejection == atomic no-op."""
    expected_category = category_of(code).value
    assert not res.prod_result.accepted
    err = res.prod_result.error
    assert err["code"] == code.value
    assert err["category"] == expected_category
    if tx_index is not None:
        assert err["tx_index"] == tx_index

    assert res.oracle_error is not None, "independent oracle unexpectedly accepted"
    assert res.oracle_error["code"] == code.value
    assert res.oracle_error["category"] == expected_category
    if tx_index is not None:
        assert res.oracle_error["tx_index"] == tx_index

    # Whole-block atomicity: production set unchanged and equal to the
    # untouched reference state.
    assert res.prod_result.state_unchanged
    assert res.prod_snapshot == res.oracle_snapshot



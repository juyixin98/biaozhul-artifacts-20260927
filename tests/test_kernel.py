def test_intra_block_double_spend_across_txs():
    sc, alice, genesis = _funded_scenario()
    bob, carol = named_key("bob"), named_key("carol")
    src = _op(genesis.transactions[0].txid, 0)
    tx1 = transfer_tx(
        [(src, alice.public_bytes)],
        [(400_000, bob.public_bytes), (599_000, alice.public_bytes)],
        {0: alice},
    )
    tx2 = transfer_tx(
        [(src, alice.public_bytes)],
        [(400_000, carol.public_bytes), (599_000, alice.public_bytes)],
        {0: alice},
    )
    cb = coinbase_tx(2, [(1_000_000, alice.public_bytes)])
    res = sc.run_target([cb, tx1, tx2])
    _assert_rejected_matches_oracle(res, ErrorCode.DOUBLE_SPEND, tx_index=2)


def test_duplicate_input_within_single_transaction():
    sc, alice, genesis = _funded_scenario()
    bob = named_key("bob")
    src = _op(genesis.transactions[0].txid, 0)
    unsigned = Transaction(
        version=1,
        inputs=(TxInput(src, b""), TxInput(src, b"")),
        outputs=(TxOutput(999_000, bob.public_bytes),),
    )
    sig = alice.sign(tx_sighash(unsigned))
    signed = Transaction(
        version=1,
        inputs=(TxInput(src, sig), TxInput(src, sig)),
        outputs=unsigned.outputs,
    )
    cb = coinbase_tx(2, [(1_001_000, alice.public_bytes)])
    res = sc.run_target([cb, signed])
    _assert_rejected_matches_oracle(res, ErrorCode.DUPLICATE_INPUT, tx_index=1)



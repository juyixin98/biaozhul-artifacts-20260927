def test_checked_add_overflow_uses_u64_bound():
    assert checked_add(5, 6, "x") == 11
    with pytest.raises(LedgerError) as ei:
        checked_add(MAX_MONEY, 1, "x")
    assert ei.value.code is ErrorCode.VALUE_OVERFLOW
    assert ei.value.category.value == "state"
    with pytest.raises(LedgerError):
        checked_add(2**63, 2**63, "x")


def test_summing_two_max_money_inputs_overflows():
    view = InMemoryChainView()
    rich = named_key("rich")
    pay = named_key("pay")
    view._utxos[(b"\x77" * 32, 0)] = Utxo(MAX_MONEY, rich.public_bytes, 1)
    view._utxos[(b"\x88" * 32, 0)] = Utxo(MAX_MONEY, rich.public_bytes, 1)
    view._tip_height = 1
    tx = transfer_tx(
        [
            (_op(b"\x77" * 32, 0), rich.public_bytes),
            (_op(b"\x88" * 32, 0), rich.public_bytes),
        ],
        [(1, pay.public_bytes)],
        {0: rich, 1: rich},
    )
    blk = Block(
        1, 2, ZERO_HASH,
        (coinbase_tx(2, [(1_000_000, rich.public_bytes)]), tx),
    )
    with pytest.raises(LedgerError) as ei:
        from utxo_ledger.kernel import validate_block

        validate_block(blk, view)
    assert ei.value.code is ErrorCode.VALUE_OVERFLOW
    assert ei.value.tx_index == 1
    # Overflow during validation must not mutate the view.
    assert view.utxo_count() == 2


def test_too_many_transactions_is_resource_category():
    sc, alice, genesis = _funded_scenario()
    raw = (
        b"UTXO-BLOCK/1\x00"
        + (1).to_bytes(4, "little")
        + (2).to_bytes(8, "little")
        + ZERO_HASH
        + (MAX_BLOCK_TXS + 1).to_bytes(4, "little")
    )
    pres = sc.node.submit_raw_block(raw, seq=123)
    assert not pres.accepted
    assert pres.error["code"] == ErrorCode.TOO_MANY_TXS.value
    assert pres.error["category"] == "resource"
    assert pres.state_unchanged


def test_sigop_budget_is_resource_category():
    """Exceeding the per-block signature-check budget is a resource error."""
    from utxo_ledger import kernel as kern

    sc, alice, genesis = _funded_scenario()
    bob = named_key("bob")
    # Drive the block with the sigops budget forced below one input's cost.
    original = kern.MAX_BLOCK_SIGOPS
    kern.MAX_BLOCK_SIGOPS = 0
    try:
        src = _op(genesis.transactions[0].txid, 0)
        tx = transfer_tx(
            [(src, alice.public_bytes)],
            [(999_000, bob.public_bytes)],
            {0: alice},
        )
        res = sc.run_target([coinbase_tx(2, [(1_001_000, alice.public_bytes)]), tx])
    finally:
        kern.MAX_BLOCK_SIGOPS = original
    assert not res.prod_result.accepted
    assert res.prod_result.error["code"] == ErrorCode.TOO_MANY_SIGOPS.value
    assert res.prod_result.error["category"] == "resource"


def test_crypto_failure_is_computation_category():
    """An unexpected backend fault is COMPUTATION, distinct from a bad sig."""
    from utxo_ledger import crypto

    alice = named_key("alice")
    # The Ed25519 verify method is a C builtin that cannot be monkeypatched on
    # the class; force a non-signature, non-material backend fault by replacing
    # the module's key loader with one raising an unexpected library error.
    original = crypto._load_public_key

    def boom(_pub):
        raise RuntimeError("simulated backend fault")

    crypto._load_public_key = boom
    try:
        with pytest.raises(LedgerError) as ei:
            crypto.verify_signature(alice.public_bytes, b"msg", b"\x00" * 64)
    finally:
        crypto._load_public_key = original
    assert ei.value.code is ErrorCode.CRYPTO_FAILURE
    assert ei.value.category.value == "computation"

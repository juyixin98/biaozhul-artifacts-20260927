def test_valid_multi_tx_block_matches_oracle():
    sc, alice, genesis = _funded_scenario()
    bob = named_key("bob")
    cb = coinbase_tx(2, [(1_001_000, alice.public_bytes)])  # subsidy + 1000 fee
    tx = transfer_tx(
        [(_op(genesis.transactions[0].txid, 0), alice.public_bytes)],
        [(400_000, bob.public_bytes), (599_000, alice.public_bytes)],
        {0: alice},
    )
    res = sc.run_target([cb, tx])
    assert res.prod_result.accepted, res.prod_result.error
    assert res.prod_result.fee_total == 1_000
    assert res.oracle_error is None
    assert res.prod_snapshot == res.oracle_snapshot
    assert len(res.prod_snapshot) == 3
    # Per-transaction reference states must match production prefix replays.
    assert res.intermediate_match
    assert len(res.prod_intermediate) == 2


def test_intra_block_back_reference_is_spendable():
    sc, alice, genesis = _funded_scenario()
    bob, carol = named_key("bob"), named_key("carol")
    tx1 = transfer_tx(
        [(_op(genesis.transactions[0].txid, 0), alice.public_bytes)],
        [(100_000, bob.public_bytes), (899_000, alice.public_bytes)],
        {0: alice},
    )  # fee 1000
    tx2 = transfer_tx(
        [(_op(tx1.txid, 0), bob.public_bytes)],
        [(99_500, carol.public_bytes)],
        {0: bob},
    )  # fee 500, spends an output created earlier in the same block
    cb = coinbase_tx(2, [(1_001_500, alice.public_bytes)])
    res = sc.run_target([cb, tx1, tx2])
    assert res.prod_result.accepted, res.prod_result.error
    assert res.oracle_error is None
    assert res.prod_snapshot == res.oracle_snapshot
    assert res.prod_result.fee_total == 1_500
    assert res.intermediate_match
    # One reference snapshot after each of the three transactions.
    assert len(res.prod_intermediate) == 3


